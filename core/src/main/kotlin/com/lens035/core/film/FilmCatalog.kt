    private val byId: Map<String, FilmRecipe> = all.associateBy { it.id }

    fun find(id: String?): FilmRecipe? = if (id == null) null else byId[id]

    fun byCategory(): List<Pair<FilmCategory, List<FilmRecipe>>> =
        FilmCategory.entries.mapNotNull { cat ->
            val list = all.filter { it.category == cat }
            if (list.isEmpty()) null else cat to list
        }
}
